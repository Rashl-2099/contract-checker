def negotiate(clause_title: str, problematic_text: str, issue_context: str, recommendation: str = "",
              legal_reference: str = "", contract_category: Optional[str] = None,
              engine: str = "auto") -> Tuple[NegotiationSession, str, Optional[str]]:
    """يعيد (جلسة التفاوض، المحرك المستخدم، رسالة تنبيه إن وجدت)."""
    if engine != "rules" and llm_available():
        try:
            return run_negotiation(clause_title, problematic_text, issue_context, contract_category), "llm", None
        except Exception as err:  # الرجوع للمحرك المحلي عند أي خطأ في الاتصال
            warning = f"تعذر الاتصال بنموذج اللغة ({type(err).__name__})، تم استخدام محاكي التفاوض المحلي."
            return offline_negotiation(clause_title, issue_context, recommendation, legal_reference, contract_category), "rules", warning
    warning = None if engine == "rules" else "لا يوجد مفتاح OpenAI صالح، تم استخدام محاكي التفاوض المحلي."
    return offline_negotiation(clause_title, issue_context, recommendation, legal_reference, contract_category), "rules", warning
